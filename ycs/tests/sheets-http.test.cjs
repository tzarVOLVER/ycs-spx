'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const express = require('express');
const path = require('node:path');
const register = require('../index.cjs');
const { normalizeSettings } = require('../public-sheets.cjs');
const { fixture } = require('./playback.test.cjs');
test('public Sheets HTTP workflow tests and maps a source without autoplay, then refreshes committed links', async t => {
  const { root, stages } = await fixture(t), app = express(); app.use(express.json());
  let value = 'SHEET ROUND', reads = 0;
  const sheets = { read: async (settings, options) => { reads++; return options?.singleCell ? { value } : { settings: normalizeSettings(settings), rows: [[{ address: 'A2', value, usable: true }]] }; } };
  const playback = register(app, { general: { dataroot: root, username: '' }, ycs: { enabled: true, dataFile: path.join(root, 'sources.json'), stages, slots: { ticker: { order: 10 }, 'lower-third': { order: 20 } } } }, { sheets, auth: { CheckLogin: (req, res, next) => next() } });
  t.after(() => playback.close());
  const server = await new Promise(resolve => { const running = app.listen(0, '127.0.0.1', () => resolve(running)); });
  t.after(() => new Promise(resolve => server.close(resolve)));
  const base = `http://127.0.0.1:${server.address().port}`;
  const post = (url, body, extra = {}) => fetch(base + url, { method: 'POST', headers: { 'Content-Type': 'application/json', ...extra }, body: JSON.stringify(body) });
  const settings = { url: 'https://docs.google.com/spreadsheets/d/1PUBLIC_SHEET_TEST_1234567890/edit#gid=42', range: 'A1:D4', refreshSeconds: 5, cell: 'A2' };
  const original = await fetch(base + '/api/ycs/data').then(response => response.json());
  assert.equal((await post('/api/ycs/data/sheets/test', { settings }, { Origin: 'https://untrusted.example' })).status, 403);
  assert.equal((await post('/api/ycs/data/sheets/test', { settings: { ...settings, url: 'http://127.0.0.1/private' } })).status, 400); assert.equal(reads, 0);
  assert.equal((await post('/api/ycs/data/sheets/test', { settings })).status, 200);
  const add = await post('/api/ycs/data/sheets', { label: 'Public round', settings, revision: original.revision });
  assert.equal(add.status, 200); const { sourceId, snapshot } = await add.json();
  assert.equal((await post('/api/ycs/data/mapping', { stage: 'stage-1', graphic: 'ticker', field: 'f5', source: sourceId, revision: snapshot.revision })).status, 200);
  for (const stage of stages) assert.equal(playback.snapshot(stage.id, 'program').graphics.length, 0);
  const links = { f5: { mode: 'linked', manual: 'MANUAL FALLBACK' } };
  assert.equal((await post('/api/ycs/stages/stage-1/graphics/ticker/preview', { links })).status, 200);
  assert.equal(playback.snapshot('stage-1', 'program').graphics.length, 0);
  assert.equal(playback.snapshot('stage-1', 'preview').graphics[0].data.f5, 'SHEET ROUND');
  assert.equal((await post('/api/ycs/stages/stage-1/graphics/ticker/play', { links })).status, 200);
  value = 'NEXT SHEET ROUND';
  assert.equal((await post(`/api/ycs/data/sheets/${sourceId}/refresh`, {})).status, 200);
  await playback.refreshLinks('stage-1');
  assert.equal(playback.snapshot('stage-1', 'program').graphics[0].data.f5, 'NEXT SHEET ROUND');
  assert.equal(playback.snapshot('stage-2', 'program').graphics.length, 0);
  assert.equal((await post('/api/ycs/data/source', { id: sourceId, value: 'CANNOT WRITE BACK', revision: snapshot.revision + 1 })).status, 422);
  const current = await fetch(base + '/api/ycs/data').then(response => response.json());
  const connectionResponse = await post('/api/ycs/data/connections', { label: 'Shared dataset', settings, revision: current.revision });
  assert.equal(connectionResponse.status, 200); const added = await connectionResponse.json();
  const mappingUrl = '/api/ycs/data/mappings/stage-1/ticker';
  const editor = await fetch(base + mappingUrl).then(response => response.json());
  assert.deepEqual(editor.fields.map(field => field.field), ['f5']);
  assert.equal((await post(mappingUrl, { revision: editor.revision, edits: [{ field: 'f0', scope: 'override', binding: null }] })).status, 422);
  const saved = await post(mappingUrl, { revision: editor.revision, edits: [{ field: 'f5', scope: 'override', binding: { connection: added.connectionId, selection: { kind: 'cell', cell: 'A2' } } }] });
  assert.equal(saved.status, 200); const mapped = await saved.json();
  assert.equal((await post(mappingUrl, { revision: editor.revision, edits: [] })).status, 409);
  assert.equal((await post(`/api/ycs/data/connections/${added.connectionId}/remove`, { revision: mapped.revision })).status, 409);
  assert.equal((await post('/api/ycs/data/connections', { id: added.connectionId, label: 'Retarget', settings: { ...settings, worksheet: '43' }, revision: mapped.revision })).status, 409);
  const unmappedResponse = await post(mappingUrl, { revision: mapped.revision, edits: [{ field: 'f5', scope: 'override', binding: null }] });
  const unmapped = await unmappedResponse.json();
  assert.equal((await post(`/api/ycs/data/connections/${added.connectionId}/remove`, { revision: unmapped.revision })).status, 200);
  assert.equal(playback.snapshot('stage-1', 'program').graphics[0].data.f5, 'NEXT SHEET ROUND', 'mapping changes and connection removal never replace the committed program binding');

});
